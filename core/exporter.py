"""Standalone web project export (files only; the plugin never runs npm).

Layout of ``<project>/export/<slug>-web/``::

    package.json, package-lock.json   viewer dependencies, exact versions (npm ci)
    index.html, src/                  the viewer source
    vite.config.ts, tsconfig.json     export versions (schema alias -> ./schema, no dev mounts)
    .env                              VITE_DEFAULT_SCENE=scene/scene.json
    schema/scene.schema.json          the contract the viewer validates against
    public/scene/                     scene.json + every file it references
    docs/                             DESIGN_SPEC.md, analysis.json, layers.json, change log,
                                      processing log (absolute paths removed), review images
    README.md, .gitignore

Every text file is scanned for absolute paths before the export is reported as done.
"""

from __future__ import annotations

import json
import re
import shutil
import zipfile
from pathlib import Path
from typing import Any

from .errors import ErrorCode, PaperCraftError
from .security import safe_id
from .version import VERSION

PLUGIN_ROOT = Path(__file__).resolve().parent.parent
VIEWER = PLUGIN_ROOT / "viewer"
TEXT_SUFFIXES = {".json", ".jsonl", ".md", ".ts", ".tsx", ".css", ".html", ".env", ".txt", ".yaml", ".yml", ""}
ABS_PATH = re.compile(r"(?<![\w:/])(/(home|Users|root|tmp|var|private|mnt)/[^\s\"'`)]+|[A-Za-z]:\\\\?[^\s\"'`)]+)")

VITE_CONFIG = '''import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import { fileURLToPath } from "node:url";

// Generated by papercraft-3d: standalone build of one scene.
export default defineConfig({
  base: "./", // works from any sub-folder of a static host
  plugins: [react()],
  resolve: {
    alias: { "@schemas": fileURLToPath(new URL("./schema", import.meta.url)) },
  },
  build: { chunkSizeWarningLimit: 1500 },
});
'''

TSCONFIG = {
    "compilerOptions": {
        "target": "ES2022", "lib": ["ES2022", "DOM", "DOM.Iterable"], "module": "ESNext",
        "moduleResolution": "bundler", "jsx": "react-jsx", "strict": True, "noUnusedLocals": True,
        "noUnusedParameters": True, "noFallthroughCasesInSwitch": True, "resolveJsonModule": True,
        "isolatedModules": True, "skipLibCheck": True, "noEmit": True, "types": ["vite/client"],
        "baseUrl": ".", "paths": {"@schemas/*": ["./schema/*"]},
    },
    "include": ["src"],
}

README = """# {name}

Interactive paper-cut scene built with [Three.js](https://threejs.org/) by the
**PaperCraft 3D** Hermes plugin (v{version}), scene revision {revision}.

## Run

Requires Node.js ≥ 20.19.

```bash
npm ci
```

```bash
npm run dev
```

Then open the URL Vite prints.

## Build and deploy

```bash
npm run build
```

`dist/` is a static site that works from any folder: upload it to GitHub Pages,
Netlify, Cloudflare Pages or any web server. Check the build locally with:

```bash
npm run preview
```

## What is inside

| Path | Content |
|---|---|
| `public/scene/scene.json` | The scene: layers, camera, lighting, interaction ({layers} layers, mode `{mode}`) |
| `public/scene/assets/`, `masks/`, `source/` | Layer images, masks and the original image |
| `schema/scene.schema.json` | JSON Schema the viewer validates `scene.json` against |
| `src/` | Viewer source (React, React Three Fiber, drei, zustand) |
| `docs/DESIGN_SPEC.md` | Design and implementation spec generated from this scene |
| `docs/` | Analysis, layer manifest, change log, processing log and review images |

You own and can edit all of it. Change values in `public/scene/scene.json`
(the viewer validates them on load), or edit the viewer in `src/`.

## Limitations

{limitations}
"""


def _strip_abs(value: Any) -> Any:
    """Replace absolute paths in log data by their file name (privacy + portability)."""
    if isinstance(value, str):
        return ABS_PATH.sub(lambda m: Path(m.group(0).replace("\\", "/")).name + " (path removed)", value)
    if isinstance(value, list):
        return [_strip_abs(v) for v in value]
    if isinstance(value, dict):
        return {k: _strip_abs(v) for k, v in value.items()}
    return value


def _copy_tree(src: Path, dst: Path) -> None:
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("node_modules", "dist", "*.tsbuildinfo", ".DS_Store"))


def scene_files(scene: dict[str, Any]) -> list[str]:
    rels = [scene["source"]["image"]]
    for layer in scene["layers"]:
        rels.append(layer["asset"])
        if layer.get("mask"):
            rels.append(layer["mask"])
        if layer.get("material", {}).get("emissiveMap"):
            rels.append(layer["material"]["emissiveMap"])
    return list(dict.fromkeys(rels))


def export(project, *, make_zip: bool) -> dict[str, Any]:
    scene = project.read_json("scene.json")
    slug = safe_id(scene["name"], fallback="scene")
    out_root = project.path("export")
    out = out_root / f"{slug}-web"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    if not (VIEWER / "package.json").is_file() or not (VIEWER / "src").is_dir():
        raise PaperCraftError(ErrorCode.EXPORT_FAILED, "The plugin's viewer source is missing; reinstall the plugin.")

    pkg = json.loads((VIEWER / "package.json").read_text(encoding="utf-8"))
    pkg["name"] = f"{slug}-papercraft"[:214]
    pkg["description"] = f"{scene['name']} — interactive paper-cut scene (PaperCraft 3D)"
    (out / "package.json").write_text(json.dumps(pkg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    if (VIEWER / "package-lock.json").is_file():
        lock = json.loads((VIEWER / "package-lock.json").read_text(encoding="utf-8"))
        lock["name"] = pkg["name"]
        if "" in lock.get("packages", {}):
            lock["packages"][""]["name"] = pkg["name"]
        (out / "package-lock.json").write_text(json.dumps(lock, indent=2) + "\n", encoding="utf-8")
    shutil.copyfile(VIEWER / "index.html", out / "index.html")
    _copy_tree(VIEWER / "src", out / "src")
    (out / "vite.config.ts").write_text(VITE_CONFIG, encoding="utf-8")
    (out / "tsconfig.json").write_text(json.dumps(TSCONFIG, indent=2) + "\n", encoding="utf-8")
    (out / ".env").write_text("VITE_DEFAULT_SCENE=scene/scene.json\n", encoding="utf-8")
    (out / ".gitignore").write_text("node_modules/\ndist/\n*.tsbuildinfo\n", encoding="utf-8")
    (out / "schema").mkdir()
    shutil.copyfile(PLUGIN_ROOT / "schemas" / "scene.schema.json", out / "schema" / "scene.schema.json")

    public = out / "public" / "scene"
    public.mkdir(parents=True)
    shutil.copyfile(project.path("scene.json"), public / "scene.json")
    for rel in scene_files(scene):
        if not project.exists(rel):
            raise PaperCraftError(ErrorCode.ASSET_MISSING, f"{rel} is referenced by scene.json but missing.")
        (public / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(project.path(rel), public / rel)

    docs = out / "docs"
    docs.mkdir()
    for rel in ("DESIGN_SPEC.md", "analysis.json", "layers.json"):
        if project.exists(rel):
            shutil.copyfile(project.path(rel), docs / Path(rel).name)
    for rel, name in (("logs/process.jsonl", "process-log.jsonl"), ("history/patches.jsonl", "change-log.jsonl")):
        if project.exists(rel):
            lines = [json.dumps(_strip_abs(json.loads(line)), ensure_ascii=False)
                     for line in project.path(rel).read_text(encoding="utf-8").splitlines() if line.strip()]
            (docs / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    if project.path("review").is_dir():
        _copy_tree(project.path("review"), docs / "review")

    limitations = "\n".join(f"- {w}" for w in [
        "A scene of transparent layers is 2.5D: front faces only, not a 3D model with back-face topology.",
        "Shadows painted into the source art are fixed; areas hidden behind nearer layers are filled in, "
        "not original image content.",
        "GLB export is not included: the layered planes would carry no more 3D information than scene.json.",
        *scene.get("warnings", []),
    ])
    (out / "README.md").write_text(README.format(
        name=scene["name"], version=VERSION, revision=scene["generator"].get("revision", 0),
        layers=len(scene["layers"]), mode=scene["mode"], limitations=limitations), encoding="utf-8")

    problems = absolute_path_leaks(out)
    if problems:
        raise PaperCraftError(ErrorCode.EXPORT_FAILED, "The export contains machine-specific absolute paths.",
                              details={"files": problems[:20]})
    files = [p for p in out.rglob("*") if p.is_file()]
    result = {"dir": out, "files": len(files), "bytes": sum(p.stat().st_size for p in files), "zip": None}
    if make_zip:
        zip_path = out_root / f"{slug}-web.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for p in sorted(files):
                zf.write(p, Path(out.name) / p.relative_to(out))
        result["zip"] = zip_path
    return result


def absolute_path_leaks(root: Path) -> list[str]:
    leaks = []
    for p in root.rglob("*"):
        if p.is_file() and p.suffix.lower() in TEXT_SUFFIXES:
            text = p.read_text(encoding="utf-8", errors="replace")
            m = ABS_PATH.search(text)
            if m:
                leaks.append(f"{p.relative_to(root)}: {m.group(0)[:80]}")
    return leaks
